# Код для вычислений и графиков 4.2
import pandas as pd
import numpy as np
from scipy import stats
import matplotlib.pyplot as plt
import seaborn as sns

# Загрузка данных
df = pd.read_csv('RGR2_A-4_X1-X4.csv', sep=';')
