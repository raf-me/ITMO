def calculate_metrics(y_true, y_pred):
    TSS = np.sum((y_true - np.mean(y_true))**2)
    RSS = np.sum((y_true - y_pred)**2)
    R2 = 1 - (RSS / TSS)
    MSE = np.mean((y_true - y_pred)**2)
    A = (100.0 / len(y_true)) * np.sum(np.abs((y_true - y_pred) / y_true))
    return R2, MSE, A

